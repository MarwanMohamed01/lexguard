// Fails if any tracked text file contains invisible or bidirectional-control characters.
// Such characters make code look different from what it does ("Trojan Source"), so a
// reviewer cannot see them. Write them as escapes instead, e.g. "\u200B".
//
// Usage: node scripts/check-hidden-chars.mjs            (check)
//        node scripts/check-hidden-chars.mjs --fix      (rewrite them as \uXXXX escapes)

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const HIDDEN =
  /[\u00AD\u061C\u180E\u200B-\u200F\u202A-\u202E\u2060-\u2064\u2066-\u2069\uFEFF\u{E0000}-\u{E007F}]/gu;
const TEXT_FILE = /\.(ts|js|mjs|json|jsonc|md|yml|yaml)$/;
// Generated by tools, not written by us.
const SKIP = new Set(["package-lock.json", "apps/worker/worker-configuration.d.ts"]);

const fix = process.argv.includes("--fix");
const files = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard"], {
  encoding: "utf8",
})
  .split("\n")
  .filter((file) => TEXT_FILE.test(file) && !SKIP.has(file));

const escape = (char) => {
  const cp = char.codePointAt(0);
  return cp > 0xffff
    ? `\\u{${cp.toString(16).toUpperCase()}}`
    : `\\u${cp.toString(16).toUpperCase().padStart(4, "0")}`;
};

let problems = 0;
for (const file of files) {
  const text = readFileSync(file, "utf8");
  text.split("\n").forEach((line, index) => {
    for (const match of line.matchAll(HIDDEN)) {
      problems++;
      console.log(`${file}:${index + 1}:${match.index + 1} hidden character ${escape(match[0])}`);
    }
  });
  const fixed = text.replace(HIDDEN, escape);
  if (fix && fixed !== text) writeFileSync(file, fixed);
}

if (problems > 0 && !fix) {
  console.error(`\n${problems} hidden character(s) found. Run with --fix to escape them.`);
  process.exit(1);
}
console.log(fix ? `Escaped ${problems} hidden character(s).` : "No hidden characters found.");
